"""Writes the WebVTT captions and the chapter/transcript module the page imports."""
import json, re, sys
out_dir = sys.argv[1]
TIM = json.load(open("timings.json"))
script = json.load(open("script.json"))

def ts(t):
    h, r = divmod(t, 3600); m, s = divmod(r, 60)
    return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"

lines = ["WEBVTT", ""]
n = 1
for cid, c in TIM["cues"].items():
    text = c["text"].replace("L L M", "LLM")
    parts = [p for p in re.split(r'(?<=[.?!])\s+(?=[A-Z"“])', text) if p]
    # merge fragments shorter than ~28 chars into their neighbour
    merged = []
    for p in parts:
        if merged and (len(p) < 28 or len(merged[-1]) < 28) and len(merged[-1]) + len(p) < 90:
            merged[-1] += " " + p
        else:
            merged.append(p)
    total = sum(len(p) for p in merged)
    t = c["start"]
    for p in merged:
        d = c["dur"] * len(p) / total
        lines += [str(n), f"{ts(t)} --> {ts(t + d)}", p, ""]
        n += 1; t += d
open(f"{out_dir}/llm-anatomy.en.vtt", "w").write("\n".join(lines))

first = lambda ch: next(s["start"] for s in TIM["scenes"] if s.get("chapter") == ch)
chapters = [
    {"t": 0, "num": "▶", "label": "Opening"},
    {"t": round(first("1.1"), 1), "num": "1.1", "label": "How an LLM works"},
    {"t": round(first("1.2"), 1), "num": "1.2", "label": "Prefill vs decode"},
    {"t": round(first("1.3"), 1), "num": "1.3", "label": "Five hidden dials"},
]
transcript = []
for sc in script:
    ch = sc.get("chapter") or ("Opening" if sc["scene"] == "title" else "Close")
    txt = " ".join(c["text"].replace("L L M", "LLM") for c in sc["cues"])
    if transcript and transcript[-1]["chapter"] == ch:
        transcript[-1]["text"] += " " + txt
    else:
        transcript.append({"chapter": ch, "text": txt})
js = "// Generated by film/gen_meta.py from the film's voice-over timings — do not edit by hand.\n"
js += f"export const FILM_DURATION = {round(TIM['total'], 1)}\n"
js += "export const FILM_CHAPTERS = " + json.dumps(chapters, ensure_ascii=False, indent=2) + "\n"
js += "export const FILM_TRANSCRIPT = " + json.dumps(transcript, ensure_ascii=False, indent=2) + "\n"
open(f"{out_dir}/filmMeta.js", "w").write(js)
print(n - 1, "captions")
